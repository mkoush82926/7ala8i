export type AdminCopy = typeof ADMIN_COPY;

/** User-facing message for an admin error code. */
export function adminErrorMessage(code: AdminErrorCode): string {
  return ADMIN_COPY.errors[code] ?? ADMIN_COPY.errors.UNKNOWN;
}

/** Human label for an audit action such as "shop.verify"; falls back to the raw code. */
export function auditActionLabel(action: string): string {
  return ADMIN_COPY.audit.actions[action] ?? action;
}
